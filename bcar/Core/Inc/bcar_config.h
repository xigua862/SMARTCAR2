#ifndef __BCAR_CONFIG_H
#define __BCAR_CONFIG_H

#include <stdint.h>

/* ---- 版本 ---- */
#define BCAR_FW_VERSION      "bcar-0.1.0"
/* 编译时间戳（__DATE__/__TIME__ 由编译器自动填）。
 * ★用途：烧完看串口横幅 / STATUS，就知道板上跑的是哪一次编译 —— 跟 hex 的文件时间一比，
 *   "烧了但没生效"一眼看穿（2026-10-15 真踩过：编译其实报错了，烧进去的还是旧镜像）。
 * ⚠ 这两行别手改，让它自动变；手改了就没有"对时间"的意义。 */
#define BCAR_FW_BUILD        __DATE__ " " __TIME__

/* ---- 时基 ---- */
#define BCAR_TICK_MS         5u      /* 控制节拍：5ms（框架 §3.1）*/
#define BCAR_SYSTICK_MS      1u      /* HAL 时基仍是 1ms，5ms 由它整除得到 */

/* ---- 串口 ---- */
#define BCAR_UART_BAUD       115200u
#define BCAR_UART_RX_BUF     256u    /* 接收环形缓冲字节数（必须是 2 的幂）*/
#define BCAR_UART_TX_BUF     192u    /* TX DMA 缓冲：够装一条 LAP 行（约 100~140 字节）*/

/* ---- 状态灯极性 ----
 * 板上 3 只 LED：GPIO → 470Ω → LED → GND，所以「输出高 = 亮」。
 * 若实测反了（亮灭相反），把这里改成 0 即可，不用改驱动。 */
#define BCAR_LED_ACTIVE_HIGH 1

/* ---- 上电行为 ----
 * 0 = 上电只做自检 + 待机，等 PC13 发车键（安全，默认）
 * 1 = 上电直接进运行状态（调试用，比赛前必须回 0） */
#define BCAR_AUTORUN_DEFAULT 0

/* ---- 电机（AT8236 ×2，TIM1 四路 PWM）---- */
#define BCAR_PWM_FREQ_HZ     20000u  /* 20kHz：超出听觉范围，且 AT8236 消隐只吃 4.4% */
#define BCAR_MOTION_MIN_MAG  50u     /* 占空比下限：低于此 AT8236 因消隐 2.2µs 不转，
                                        所以 mag 有效范围是 50~1000 而不是 0~1000 */
#define BCAR_MAG_MAX         1000u

/* ---- 风机（负压/下压力）----
 * 板上有这条路：PB1/PB2 → 47Ω → 第 3 颗 AT8236(U6) → NPF1/NPF2 接风机（用户 2026-10-15 确认）。
 * 用途：这台车后驱 + 静摩擦大，起步那一脚会把车头抬起来（"翘头严重"）⇒ 车头一抬灰度就看不见线。
 * 现在：**进发车读秒就开**（留出风机转起来的时间），离开 RUN 就关（5Ω 的风机 ≈ 2.5A，别常开）。
 * ★方向：1 = IN1 高；2 = IN2 高。哪个是"往下压"要台上试 —— 敲 `FAN 1` / `FAN 2`
 *   看风往哪吹（或用纸片/手感），把对的那个数写到这里（试完告诉我，我编进去）。 */
#define BCAR_FAN_DIR         0u      /* ⚠ 0 = 风机停用（2026-10-15 实测：这台风机的驱动被限流
                                        * 卡住、只会嗡嗡抖不转，判为坏件）。修好后改 1 或 2。 */
/* 风机占空比（0~1000）。★不许写 1000：那又变成"恒定高电平"了，AT8236 高边会垮、
 * 风机就不转（2026-10-15 实测踩过）。默认 800 = 每 5ms 周期里 1ms 低电平"续命"。 */
#define BCAR_FAN_DUTY      800u

/* 电机方向整体翻转开关 —— ★2026-10-15 实测定案 = 1（原来是 0，错的就是这里）。
 * 判据（推车法，都是芯片里的原始计数）：
 *   朝车头推 1.00m → 编码器计数【变正】
 *   MOTOR FWD 1 秒 → 编码器计数【变负】
 *   ⇒ 软件说的"正转"实际是往后走。后果不只是"倒着跑"：差速转向也跟着反，
 *     车会朝**远离线**的方向拐（用户早就报过"轮子方向也是错的"）。
 * 改 1 之后：FWD = 朝车头 = 编码器计数递增，转向、里程、发车方向三者才自洽。
 * 两只电机一起翻，不要分别改线。 */
#define BCAR_MOTOR_DIR_FLIP  1

/* ---- 蜂鸣器（PB10 → 1kΩ → SS8050 低边 → 5V 有源蜂鸣器）---- */
#define BCAR_BUZZER_ON_LEVEL 1u      /* 输出高 = 三极管导通 = 响 */

/* ---- 按键消抖 ---- */
#define BCAR_KEY_DEBOUNCE_MS 15u     /* 连续稳定 15ms 才算数（主循环 5ms 一拍 → 3 拍）*/

/* ---- 发车读秒里自动标一次陀螺零偏（2026-10-15 加）----
 * 为什么要：2026-10-15 在台上用串口实测（车静止 45 秒），陀螺 Z 的原始零偏 ≈ **0.4 dps**；
 *   不标定就直接积分 ⇒ 航向以 0.4°/s 漂，跑一圈（约 40 秒）就能飘掉约 16° ——
 *   "惯导为主"的设计会直接垮掉，而且**不报错**，只在赛道上表现为"怎么调都跑不直"。
 * 怎么用：发车读秒那 3 秒车本来就刹着不动，正好采 1 秒静止样本把零偏标掉；
 *   采集期间若车明显被碰/在转（样本极差 > BCAR_GYRO_AUTOCAL_MAX_SPREAD_DPS），
 *   本次**放弃**自动标定、沿用原零偏，并在串口说明（宁可不标，也不标一个错的）。
 * 不想要就把开关改 0：那时只认台上手敲的 GYROZERO。 */
#define BCAR_GYRO_AUTOCAL_ON_LAUNCH        1
#define BCAR_GYRO_AUTOCAL_MAX_SPREAD_DPS   1.0f

/* ---- 按键长按门限（发车流程，2026-10-15 需求）----
 * PC13（KEY2 / 正式发车键）**长按 200ms 才发车，短按不响应**；
 * 短于这个时长的按下只报一次"短按"（串口提示一句），不发车。 */
#define BCAR_KEY_LONG_MS     200u

/* ---- 发车流程（按键 → 读秒 → 循迹）----
 * 时序（哪一声、隔多久）在 `src/app/launch.c` 里；这里只定"响多久"这种物理量。
 * 读秒节奏 = 短 2 声 + 长 1 声（用户 2026-10-15 定）。 */
#define BCAR_BEEP_SHORT_MS   80u     /* "哔"：读秒前两声、测试模式的每一声 */
#define BCAR_BEEP_LONG_MS    600u    /* "哔——"：读秒第 3 声 = 松手起跑那声 */
#define BCAR_BEEP_GAP_MS     120u    /* 连鸣两声之间的间隔（测试模式"哔 哔"）*/

/* ---- 里程标定（★必须实测，现在这个值是猜的）----
 * 标定方法：把车推 1 米（1000mm），看串口 `ENC` 的 total 涨了多少计数，
 *           然后 mm_per_count = 1000 / 那个计数，改这里重新编译。
 * ⚠ v1.8 更正：编码器是**齿轮驱动**（不是装轮轴），老的 πD/4096 不成立。 */
/* ★2026-10-15 实测标定（推车法）：朝车头推 1.00m = 201330 个计数 ⇒ 200 计数/mm。
 *   ⚠ 编码器是**齿轮驱动**的，别拿 πD/4096 去算（算出来差 20 倍）。
 *   换电机/换编码器/改齿轮都要重新推一次。 */
#define BCAR_MM_PER_COUNT    (1000.0f / 201330.0f)
#define BCAR_TRACK_MM      110.0f    /* 轮距 110mm（实测真值）*/

/* ---- 陀螺（IMU660RC / LSM6DSV16X）---- */
#define BCAR_GYRO_DEAD_ZONE_DPS   0.3f   /* 死区：减掉零偏后小于它当 0，抑制噪声积分漂移 */
#define BCAR_GYRO_CAL_MS          1000u  /* 上电自检 / GYROZERO 的静止采集时长 */
#define BCAR_GYRO_CAL_SAMPLES     (BCAR_GYRO_CAL_MS / BCAR_TICK_MS)  /* 采集样本数 */

/* ---- 灰度 8 路（PA0~PA7，模块供 5V、板上 1k/1.5k 分压）----
 * ★★2026-10-15 深夜：在**真赛道材料**上实测出逐路黑白基准，已当默认值写死。
 *   怎么测的（照着复测）：
 *     ① 整车放到"纯黑底布"上（离白线/斑马线 ≥10cm，**整排 8 路都在黑布上**）→ 敲 `IRBLACK`
 *     ② 把车**转 90°**，让**白线顺着探头排的方向**从 8 路下面穿过（8 路都在线上）→ 敲 `IRWHITE`
 *        （⭐这一步是诀窍：白线只有 25mm 宽，正常摆位永远只压住 2 路，教不全 8 路）
 *   换布/换模块/改探头高度 → 必须重量，改下面这两行数组。
 * ⚠ 这模块的输出是"**越黑电压越高**"（黑底能把输出顶到 5V 饱和 = raw≈3750；白线≈30），
 *   跟"白高黑低"的直觉相反 —— 别按直觉改数组。
 * ⚠ ch6（数组第 7 个）是**弱路**：黑值只有 ~415、和线的对比度 ~380 LSB，跑起来可能抖；
 *   实测时它的黑值在 194~415 之间飘（探头高度敏感）。真要更稳，只能改结构让探头更贴地。 */
#define BCAR_IR_BLACK_ARR { 3755.0f, 495.0f, 645.0f, 299.0f, 474.0f, 2814.0f, 415.0f, 1278.0f }
#define BCAR_IR_WHITE_ARR {   30.0f,  36.0f,  30.0f,  26.0f,  29.0f,   40.0f,  28.0f,   37.0f }

/* 探头间距（相邻两探头中心距）。
 * ★2026-10-15 **用户实测**：以车正中线为 0、左负右正，8 路位置 =
 *   -38.5 / -27.5 / -16.5 / -5.5 / +5.5 / +16.5 / +27.5 / +38.5 mm
 *   ⇒ 间距 = 11.0mm，且对称中心正好落在 ch3/ch4 之间（(k−3.5)×11 能还原整张表）。
 *   占位值原来是 6.0（错近一倍），会让 err_mm 和转向力度一起错一倍。 */
#define BCAR_IR_PITCH_MM     11.0f
#define BCAR_IR_LOST_SUM_P   0.4f   /* Σp 低于它判丢线 */
#define BCAR_IR_CAL_SAMPLES  20u    /* 现场"教黑白"时每路平均的样本数 */

/* ---- 循迹控制（阶段 7 起步版：只闭环转向，速度先固定）---- */
#define BCAR_CTRL_BASE_MAG     350u    /* 起步速度：先慢。能跑通一圈再往上提 */
/* ★2026-10-15 深夜下调：原来是 25/3，那是按"err 用占位间距 6mm"定的；间距改成实测
 * 11mm 后 err 数值大了近一倍 ⇒ 同一个 kp 打出的转向量翻倍 ⇒ 现场"瞎甩头"。
 * 现在 10/1.5 起步（10mm 偏差 → 转向量 100，约为 BASE 的 1/3），现场用 `PD` 命令往上找。 */
#define BCAR_CTRL_KP           10.0f   /* 转向 P：mag / mm */
#define BCAR_CTRL_KD            1.5f   /* 转向 D：mag / mm */
#define BCAR_CTRL_STEER_MAX   350.0f   /* 转向量限幅（≈BASE：最狠也就是内侧轮停住，不许反转）*/
/* 循迹环方向：1 = 默认（err>0 = 线在右 ⇒ 往右打）。车上如果发现"朝远离线的方向拐"，
 * 台上敲 `LSDIR 2` 翻过来，不用重烧。 */
#define BCAR_CTRL_LINE_SIGN      1

/* ---- 过 S / 到 G 停车（2026-10-15 加，用户口径：过 S 触发一次、到 G 再触发就停）----
 * 判据与常数都有实测量撑腰（见 zebra.h）：斑马线上 7 路白、白区跨度 77mm、sum_p≈6.4；
 * 普通白线最多 4 路、跨度 ≤33mm、sum_p≈2.8。 */
#define BCAR_MARK_S_WINDOW_MM   1500.0f   /* S 离发车点约 224mm：第一条只在这个窗口内认 */
#define BCAR_FINISH_MIN_MM     25000.0f   /* 第二条要过了这么远才算"到 G"（一圈 37.11m）*/
#define BCAR_FINISH_ODOM_MM    36500.0f   /* ★里程兜底：斑马线没认出来也别跑飞，到这就停 */

/* ---- 里程只用单编码器（★临时，右编码器坏了）----
 * 右编码器现在**读不到数**（硬件待查）。若还按 (dL+dR)/2 算，里程只有真实的一半，
 * "跑完一圈停车"的里程兜底就永远不会触发。修好右编码器后把这里改回 0。 */
#define BCAR_ODOM_SINGLE_ENC   1

/* ---- 起步助推（kickstart，2026-10-15 实测加）----
 * 为什么需要：这台车**静摩擦大**。串口实测（左电机，用编码器计数当判据）：
 *     从停到动：40% 不动、60% 不动、**80% 才转**；
 *     但满力踹 0.25 秒之后再降到 **30% 就能一直维持**（编码器持续在涨）。
 *   ⇒ "巡航速度"没问题（30% 够），卡的是**起步那一下**。
 * 做法：只要车"从停着变成要动"（进 RUN、或刹停之后再起步），先给
 *   `BCAR_CTRL_KICK_MS` 毫秒的 `BCAR_CTRL_KICK_MAG`（转向照常参与），然后回到 BASE。
 * 代价：起步那一脚会往前多冲几厘米（150ms × 80% ≈ 5~10cm），发车点别贴着障碍。
 *   机械上若能弄顺（轴承/齿轮/轮子蹭框架），这脚可以调小甚至关掉（改 0 即等于关）。 */
#define BCAR_CTRL_KICK_MAG     800u    /* 起步斜坡的顶端（实测 80% = 800 能起来）*/
#define BCAR_CTRL_KICK_MS      400u    /* 斜坡时长（原来 60ms"踹一脚"）。
                                        * 150ms 时后驱扭矩把车头抬起来了（用户报"翘头严重"），
                                        * 缩短到 60ms：只要够"破静摩擦"就行，剩下的交给 BASE。 */

/* ---- 速度环（PI，用左编码器实测速度当反馈）★2026-10-15 深夜加 ----
 * 为什么：这台车静摩擦大，"起步之后会停"（BASE 挡不住地面摩擦），而且换电池/换地面就变。
 *   速度环让积分自动把占空比加到"车真的动"，等于把摩擦当扰动抵消掉
 *   （这就是 ADRC 的思路，但参数从 6 个降到 2 个，赛前才调得动）。
 * 现场调：`SPD <mm/s>` 改目标速度；`SPD 0` 关掉速度环（退回手动 BASE）。 */
/* ★增益是单测压出来的：1.2/6.0 在"车 1 mm/s 每 mag、静摩擦 400"的模型上会震荡，
 *  降到 0.6/2.0 后：既能破摩擦（积分 ~0.4 秒把输出顶过 400），又不震荡。 */
#define BCAR_VEL_KP          0.6f     /* P：mag / (mm/s)，误差 100mm/s → 60 */
#define BCAR_VEL_KI          2.0f     /* I：mag / mm（按秒积分）—— 破静摩擦主要靠它 */
#define BCAR_VEL_MIN_MAG    380u      /* 输出下限：实测这车低位推不动，别让它白绕积分 */
#define BCAR_VEL_MAX_MAG   1000u
#define BCAR_V_TARGET_MS    300.0f    /* 巡航目标速度 mm/s（慢点先：37m 一圈 ≈ 2 分钟）*/
#define BCAR_V_RAMP_MS      600u      /* 起步时目标速度 0→目标 的斜坡（软起，压翘头）*/
#define BCAR_VEL_ON             1     /* 1 = 用速度环（推荐）；0 = 退回"斜坡 + 手动 BASE" */

/* ---- 陀螺直行（航向保持，2026-10-15 晚加）----
 * 干什么：看不到线的时候（发车起步 / 丢线 / 过斑马线断开）**不刹车**，
 *         用陀螺保持"当时那个航向"直着走，一看到线立刻交回循迹环。
 * 为什么要：之前丢线只撑 200ms 就刹死 ⇒ 按 PC13 发车后车"不动"（桌面上没线）。
 * 符号：yaw 逆时针为正、转向量 >0 = 往右打 ⇒ `sign = +1` 时
 *       steer = kp×(yaw − 目标)，车头偏左就往右纠。
 *       ★台上若发现"车往越偏越远的方向打"（画龙/掉头），先敲 `SDIR -1` 试试，
 *        那就是陀螺或电机装反了，**不用回电脑重烧**。 */
/* ★2026-10-15 深夜：**陀螺直行先关掉**（用户："先把普通循迹调通，直线都走不明白怎么跑"）。
 * 关掉之后 RUN 里就只剩"灰度 PD"，看不到线就直着走一段再刹车 —— 变量少、好定位。
 * 调顺了想开回来：`GYRO 1`（现场一条命令）或把这里改 1。 */
#define BCAR_STR_ON             0

#define BCAR_STR_KP            12.0f   /* P：mag / 度（偏 10° → 打 120）*/
#define BCAR_STR_KD             1.5f   /* D：mag / (度/秒)（抑震荡）*/
#define BCAR_STR_STEER_MAX    600.0f   /* 直行也用同一套限幅 */
#define BCAR_STR_SIGN             1    /* +1 / -1（台上一键翻，见上）*/
#define BCAR_STR_LOST_MS       2500u   /* 丢线后最多直行找线 2.5 秒，超了才刹车（兜底）*/
#define BCAR_STR_LOST_BASE_P    1.0f   /* 丢线找线时的速度系数。
                                        * ⚠ 原来 0.6：但这台车**维持转动至少要 30% 占空比**
                                        *（实测 300 才维持得住），0.6×350=210 会直接停住 ⇒ 改 1.0。
                                        * 想减速只能靠 BASE 本身，不能再打折。 */

#endif /* __BCAR_CONFIG_H */
