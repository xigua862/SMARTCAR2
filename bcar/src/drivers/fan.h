/**
  ******************************************************************************
  * @file    fan.h
  * @brief   风机（负压/下压力）驱动 —— PB1/PB2 → 47Ω → 第 3 颗 AT8236 → 风机
  *
  * 板上实际是有这条路的（用户 2026-10-15 确认原理图）：U6 = 第 3 颗 AT8236，
  *   PB1 → 47Ω → IN1，PB2 → 47Ω → IN2，OUT1/OUT2（NPF1/NPF2）接风机。
  *
  * 为什么要它：这台车**后驱 + 静摩擦大**，起步那一脚（kickstart）会把车头抬起来
  *   （用户："翘头严重"）—— 车头一抬，灰度就看不见线了，所以必须压住。
  *
  * 注意两点：
  *   ① PB1/PB2 是**普通 GPIO**，不是 PWM：TIM3 被右编码器占了（编码器模式），
  *      所以风机只有"开/关"两档（对风机够用）。
  *   ② 风机 5Ω ≈ **2.5A**，别一直开着：现在只在"发车读秒开始 → 离开 RUN"这段时间开。
  *
  * 方向（正吹/反吹）：由 `BCAR_FAN_DIR` 定，台上用串口 `FAN 1` / `FAN 2` 试出来
  *   （哪个方向是"往下压"就留哪个）。
  ******************************************************************************
  */
#ifndef __DRV_FAN_H
#define __DRV_FAN_H

#include <stdint.h>

/** @brief 初始化 PB1/PB2 为推挽输出并关掉风机 */
void fan_init(void);

/**
  * @brief  直接设档位
  * @param  level 0 = 关（两脚都低，风机滑行）；1 = 正吹；2 = 反吹
  */
void fan_set(uint8_t level);

/** @brief 按"记住的方向"开（发车时用这个）*/
void fan_launch_on(void);

/** @brief 关 */
void fan_off(void);

/** @brief 设"发车时用哪个方向"（0/1/2），并立即生效 */
void fan_set_dir(uint8_t level);

/** @brief 当前档位（0/1/2）*/
uint8_t fan_level(void);

/**
  * @brief  软件 PWM 的 1ms 心跳（**放在 SysTick 中断里调**）
  * @note   为什么要 PWM 而不是静态电平：AT8236 这类芯片的高边要靠不断开关来维持
  *         （自举/电荷泵），**给一个恒定的高电平，输出会慢慢垮掉 ⇒ 风机不转**。
  *         电机通道一直是 PWM（20kHz）所以没事；风机是 GPIO，只能软件 PWM。
  *         周期 5ms（200Hz）、占空比 1/5 ~ 4/5 —— 每周期都至少有一段低电平给高边"续命"。
  */
void fan_tick_isr(void);

#endif /* __DRV_FAN_H */
