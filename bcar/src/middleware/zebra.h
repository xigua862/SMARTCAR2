/**
  ******************************************************************************
  * @file    zebra.h
  * @brief   斑马线（S/G 地标）检测 —— **纯逻辑，无硬件依赖，可在 PC 上单测**
  *
  * 判据从赛道图量出来（不是猜的）：
  *   - 普通白线：宽 25mm。8 路探头间距 11mm、位置 ±5.5/±16.5/±27.5/±38.5mm，
  *     所以一条普通线最多同时压 3 路、"白区跨度"最多 ~22mm（斜着压最多 ~33mm）。
  *   - S / G 斑马线：**100mm 宽的"梯子"**（白条 ~18mm、间隔 ~50mm，横跨整条赛道），
  *     车压上去时"白条 + 中间那条线"会同时亮好几路，**跨度和路数都明显超过一条线**。
  *
  * 为什么要它：用户要的口径 —— 过 S 触发一次"斑马线"判定；跑完一圈到 G 再触发 → 停车。
  *
  * ⚠ 局限（写清楚了别被坑）：白条只有 18mm、间隔 ~50mm，车横着停的位置不同，
  *   探头排可能只压到 1 条白条 —— 那一次就可能"看不出来"。所以**里程兜底不能省**
  *   （见 main.c 的判定：斑马线 OR 里程到 → 停）。
  *
  * 本文件不许 #include 任何 stm32/HAL/驱动头文件 —— 硬纪律（保证 PC 可单测）。
  ******************************************************************************
  */
#ifndef __MW_ZEBRA_H
#define __MW_ZEBRA_H

#include <stdint.h>
#include "line_pos.h"

/* ★判据全部按 2026-10-15 的**实测**定，不是按图上估的（估的那个在真白线上会误报）：
 *   白线正中  p = 0  0  0.66 0.94 0.96 0.14 0.61 0    sum_p=3.33  强白(p≥0.85)只有 ch3/ch4，跨度 11mm
 *   斑马线上  p = 0.99 0.40 0.69 0.94 0.95 0.76 0.66 0.95 sum_p=6.40 强白 ch0/ch3/ch4/ch7，跨度 77mm
 *   （白线之所以也有 44mm 的"弱白跨度"，是探头相互照到邻居那点亮 —— 所以只认**强白**）*/
#define ZEBRA_P_STRONG       0.85f   /* "强白"：p ≥ 0.85 才算真压着白 */
#define ZEBRA_MIN_STRONG_CH  2u      /* 强白至少这么多路 */
#define ZEBRA_MIN_SPAN_MM    55.0f   /* 强白跨度要 ≥ 它（白线 11mm，斑马线 77mm）*/
#define ZEBRA_MIN_SUM_P      4.5f    /* 同时总白量也要够（白线 3.3，斑马线 6.4）*/
/* 连续这么多拍才算数（15ms 去抖）*/
#define ZEBRA_ON_TICKS       3u
/* 离开这么久之后才算"这一条过完了"，好让下一次过线能再报一次 */
#define ZEBRA_OFF_TICKS      25u

typedef struct {
    uint8_t  inside;      /* 1 = 当前认为正压在斑马线上 */
    uint16_t on_ticks;    /* 连续满足判据的拍数 */
    uint16_t off_ticks;   /* 连续不满足的拍数 */
} zebra_t;

void zebra_init(zebra_t *z);

/**
  * @brief  每拍喂一次灰度结果
  * @param  lp 这一拍的 line_pos 输出（含 8 路 p 值和 visible）
  * @retval 1 = **这一拍刚判定"压上斑马线"**（事件只报一次，不是电平）
  */
uint8_t zebra_step(zebra_t *z, const line_pos_t *lp);

/** @brief 当前是否正压在斑马线上（诊断用）*/
uint8_t zebra_inside(const zebra_t *z);

#endif /* __MW_ZEBRA_H */
