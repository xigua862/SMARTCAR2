/*********************************************************************************************************************
* 文件名:      eeprom_data.h
* 说明:        EEPROM 数据存取模块
*              基于逐飞库 zf_driver_eeprom(IAP) 底层驱动, 提供两层功能:
*              1. 通用类型读写接口: 8/16/32 位整型、32 位浮点(小端字节序)
*              2. 菜单参数块整体保存/恢复(带魔数+版本号+校验和)
* 设计说明:    数据以"内存视图"方式直接读写 —— 通过联合体 eeprom_val_t 与 EEPROM 字节
*              内存一一对应, 由编译器直接处理内存布局, 无需手动拼接/拆分字节;
*              整型/浮点均按本机小端序存储(与逐飞库底层字节流天然一致)。
* 适用平台:    STC32G (AI32G12K128)
* 修改记录:
* 日期          作者         备注
* 2026.8.31     get_lucky()  更新文件头注释
*********************************************************************************************************************/

#ifndef EEPROM_DATA_H
#define EEPROM_DATA_H

#include "zf_common_typedef.h"

//-------------------------------------------------------------------------------------------------------------------
// EEPROM 容量配置 (需与 STC-ISP 下载时设置的 EEPROM 分区大小一致, 本工程按 1KB 设计)
// 若实际分区更大, 只需改大 EEPROM_SIZE_BYTES 即可(同时保证通用区不超出容量)。
//-------------------------------------------------------------------------------------------------------------------
#define EEPROM_SIZE_BYTES            (1024u)         // EEPROM 总容量(字节), 地址范围 0x0000-0x03FF
#define EEPROM_SECTOR_SIZE           (512u)          // 扇区大小(字节), 擦除以扇区为单位

// 地址分区规划:
//   扇区0  0x0000-0x01FF  参数块(菜单参数整体保存/恢复, 供 sys_param_* 系列使用)
//   扇区1  0x0200-0x03FF  通用类型读写区(供 eeprom_read_*/eeprom_write_* 系列使用)
#define EEPROM_PARAM_BASE            (0x0000u)       // 参数块起始地址
#define EEPROM_GENERIC_BASE          (0x0200u)       // 通用类型区起始地址

//-------------------------------------------------------------------------------------------------------------------
// 数据联合体: 与 EEPROM 字节内存直接对应, 读写时无需手动拼接字节
// 整型/浮点均按本机小端字节序存储(低字节在低地址), 有符号整型位模式相同
// 用法示例:
//   eeprom_val_t v;
//   v.f32 = 3.14f;
//   eeprom_write_buff(EEPROM_GENERIC_BASE, v.bytes, 4);   // 写入
//   eeprom_read_buff(EEPROM_GENERIC_BASE,  v.bytes, 4);   // 读回
//   // v.f32 == 3.14f
//-------------------------------------------------------------------------------------------------------------------
typedef union
{
    uint8   u8;                     // 8 位整型
    uint16  u16;                    // 16 位整型
    uint32  u32;                    // 32 位整型
    float   f32;                    // 32 位浮点
    uint8   bytes[4];               // 内存字节视图(小于 4 字节的类型按实际长度读写)
} eeprom_val_t;

//-------------------------------------------------------------------------------------------------------------------
// 通用接口
//-------------------------------------------------------------------------------------------------------------------
// 直接读写多个字节(内存视图, 适合结构体/联合体/数组整体存取)
// 注意: 写入内部自动完成"读扇区->改->擦除->写回", 调用方无需手动擦除;
//       越界或跨扇区时直接返回, 不写入。
void    eeprom_read_buff(uint16 addr, uint8 *buf, uint16 len);
void    eeprom_write_buff(uint16 addr, uint8 *buf, uint16 len);

// 8/16/32 位整型与 32 位浮点便捷接口 (底层均走 eeprom_read/write_buff)
uint8   eeprom_read_u8(uint16 addr);
void    eeprom_write_u8(uint16 addr, uint8 val);
uint16  eeprom_read_u16(uint16 addr);
void    eeprom_write_u16(uint16 addr, uint16 val);
uint32  eeprom_read_u32(uint16 addr);
void    eeprom_write_u32(uint16 addr, uint32 val);
float   eeprom_read_f32(uint16 addr);
void    eeprom_write_f32(uint16 addr, float val);

// 擦除 addr 所在扇区(512 字节)
void    eeprom_erase_sector(uint16 addr);

//-------------------------------------------------------------------------------------------------------------------
// 参数块接口 (菜单参数整体保存/恢复)
//-------------------------------------------------------------------------------------------------------------------
void    eeprom_init(void);          // EEPROM 初始化(使能 IAP), 开机调用一次
void    sys_param_load(void);       // 上电加载参数, 校验失败(首次上电/数据损坏)自动恢复出厂默认值
void    sys_param_save(void);       // 保存当前参数到 EEPROM
void    sys_param_reset(void);      // 恢复出厂默认值(写回 EEPROM 并立即生效)

#endif
