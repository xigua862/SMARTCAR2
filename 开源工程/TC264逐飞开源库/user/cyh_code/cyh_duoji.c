
#include "zf_common_headfile.h"
#include "cyh_headfile.h"

// **************************** 代码区域 ****************************

int duty,duty2,duty_chasu;


//-------------------------------------------------------------------------------------------------------------------
// 函数简介     舵机初始化
// 参数说明
// 返回参数
// 使用示例     duoji_int();
// 备注信息
//-------------------------------------------------------------------------------------------------------------------

void duoji_int(void)
{
    pwm_init ( ATOM0_CH1_P33_9 , 300, duojizhongzhi*6);
    pwm_init ( ATOM2_CH5_P33_13 , 300, 0);
    pwm_init ( ATOM1_CH5_P32_4 , 300, 0);
    duty=0;//700-810
    duty2=0;
    duty_chasu=0;
}

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     舵机pwm输出
// 参数说明
// 返回参数
// 使用示例     duoji_out();
// 备注信息
//-------------------------------------------------------------------------------------------------------------------
void duoji_out(void)
{
    pwm_set_duty (ATOM0_CH1_P33_9,(duojizhongzhi+duty)*6);
}



